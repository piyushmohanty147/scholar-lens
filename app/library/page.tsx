"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { supabase } from "../../lib/supabase";

type Rec = Record<string, unknown>;
type SavedReport = { id: string; project: string; audience: string | null; horizon: string | null; created_at: string; result: Rec };
type SavedPaper = { paper_id: string; title: string; year: number | null; authors: string[] | null; venue: string | null; url: string | null; summary: string | null; created_at: string };

const str = (x: unknown) => (typeof x === "string" ? x : "");
const arr = (x: unknown): unknown[] => (Array.isArray(x) ? x : []);
const obj = (x: unknown): Rec => (x && typeof x === "object" ? (x as Rec) : {});
const cite = (x: unknown) => { const ids = arr(x).map(str).filter(Boolean); return ids.length ? ` [${ids.join(", ")}]` : ""; };

function reportToMarkdown(r: SavedReport): string {
  const res = r.result;
  const rep = obj(res.report);
  const sources = arr(res.sources).map(obj);
  const L: string[] = [];
  L.push(`# Project outlook`, "", `**Project:** ${r.project}`, `**Horizon:** ${r.horizon ?? ""} year(s)  `, `**Date:** ${new Date(r.created_at).toLocaleDateString()}`, "");
  if (str(rep.summary)) L.push("## Summary", "", str(rep.summary), "");
  if (str(rep.bottomLine)) L.push(`**Bottom line:** ${str(rep.bottomLine)}`, "");

  const items = (title: string, list: unknown, withAction?: string) => {
    const a = arr(list).map(obj);
    if (!a.length) return;
    L.push(`## ${title}`, "");
    for (const i of a) {
      L.push(`- **${str(i.point)}** ${str(i.why)}${cite(i.sources)}${str(i.strength) ? ` _(evidence: ${str(i.strength)})_` : ""}`);
      if (withAction && str(i.action)) L.push(`  - ${withAction}: ${str(i.action)}`);
    }
    L.push("");
  };

  const trends = arr(rep.trends).map(obj);
  if (trends.length) { L.push("## Trends", ""); for (const t of trends) L.push(`- **${str(t.name)}** (${str(t.direction)}): ${str(t.evidence)}${cite(t.sources)}`); L.push(""); }
  const cons = arr(rep.consensus).map(obj);
  if (cons.length) { L.push("## What the research agrees on", ""); for (const c of cons) L.push(`- ${str(c.point)}${cite(c.sources)}`); L.push(""); }
  items("Open debates", rep.debates);
  items("Opportunities", rep.opportunities, "How to act");
  items("Risks", rep.risks, "How to reduce it");

  const sc = arr(rep.scenarios).map(obj);
  if (sc.length) {
    L.push("## Scenarios", "");
    for (const s of sc) {
      L.push(`- **${str(s.name)}** (likelihood: ${str(s.likelihood)}, confidence: ${str(s.confidence)}): ${str(s.description)}`);
      const d = arr(s.drivers).map(str).filter(Boolean); if (d.length) L.push(`  - Drivers: ${d.join("; ")}`);
      const g = arr(s.signals).map(str).filter(Boolean); if (g.length) L.push(`  - Signs it is happening: ${g.join("; ")}`);
    }
    L.push("");
  }
  const tl = arr(rep.timeline).map(obj);
  if (tl.length) { L.push("## Timeline", ""); for (const t of tl) L.push(`- **${str(t.period)}:** ${str(t.expect)}`); L.push(""); }
  const ind = arr(rep.indicators).map(obj);
  if (ind.length) { L.push("## Indicators to track", ""); for (const t of ind) L.push(`- **${str(t.signal)}** ${str(t.why)}`); L.push(""); }
  const na = arr(rep.nextActions);
  if (na.length) { L.push("## Next actions", ""); for (const a of na) { if (typeof a === "string") L.push(`- ${a}`); else { const o = obj(a); L.push(`- ${str(o.when) ? `**${str(o.when)}:** ` : ""}${str(o.action)}`); } } L.push(""); }
  const q = arr(rep.questionsForExperts).map(str).filter(Boolean);
  if (q.length) { L.push("## Questions to ask experts", ""); for (const x of q) L.push(`- ${x}`); L.push(""); }
  const gaps = arr(rep.gaps).map(str).filter(Boolean);
  if (gaps.length) { L.push("## What this evidence does not cover", ""); for (const x of gaps) L.push(`- ${x}`); L.push(""); }
  const gl = arr(rep.glossary).map(obj);
  if (gl.length) { L.push("## Glossary", ""); for (const g of gl) L.push(`- **${str(g.term)}:** ${str(g.meaning)}`); L.push(""); }
  if (sources.length) {
    L.push("## Sources", "");
    for (const s of sources) L.push(`- [${str(s.id)}] ${str(s.title)}${typeof s.year === "number" ? ` (${s.year})` : ""}${str(s.url) ? ` ${str(s.url)}` : ""}`);
    L.push("");
  }
  L.push(`_${str(rep.caveat) || "Research activity is not the same as real-world outcomes."} This is an informed outlook based on published research, not a guarantee or financial advice. Generated by Scholar Lens._`);
  return L.join("\n");
}

function bibtex(p: SavedPaper): string {
  const authors = p.authors ?? [];
  const last = (authors[0] ?? "anon").split(" ").pop()?.toLowerCase().replace(/[^a-z]/g, "") || "anon";
  const word = p.title.toLowerCase().replace(/[^a-z0-9 ]/g, "").split(" ").find((w) => w.length > 3) ?? "paper";
  const clean = (s: string) => s.replace(/[{}]/g, "");
  const lines = [`@article{${last}${p.year ?? ""}${word},`, `  title = {${clean(p.title)}},`];
  if (authors.length) lines.push(`  author = {${authors.map(clean).join(" and ")}},`);
  if (p.year) lines.push(`  year = {${p.year}},`);
  if (p.venue) lines.push(`  journal = {${clean(p.venue)}},`);
  if (p.url) lines.push(`  url = {${p.url}},`);
  lines.push("}");
  return lines.join("\n");
}

function download(name: string, text: string, mime: string) {
  const url = URL.createObjectURL(new Blob([text], { type: mime }));
  const a = document.createElement("a");
  a.href = url; a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  URL.revokeObjectURL(url);
}

export default function Library() {
  const [reports, setReports] = useState<SavedReport[]>([]);
  const [papers, setPapers] = useState<SavedPaper[]>([]);
  const [shares, setShares] = useState<Record<string, string>>({});
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [note, setNote] = useState("");

  useEffect(() => {
    let alive = true;
    (async () => {
      const [r, p, s] = await Promise.all([
        supabase.from("saved_reports").select("id,project,audience,horizon,created_at,result").order("created_at", { ascending: false }).limit(50),
        supabase.from("saved_papers").select("paper_id,title,year,authors,venue,url,summary,created_at").order("created_at", { ascending: false }).limit(200),
        supabase.from("shared_reports").select("report_id,token"),
      ]);
      if (!alive) return;
      if (r.error || p.error) setError("Could not load your library. Make sure the database setup was run, then refresh.");
      setReports((r.data as SavedReport[] | null) ?? []);
      setPapers((p.data as SavedPaper[] | null) ?? []);
      const map: Record<string, string> = {};
      for (const row of (s.data as { report_id: string; token: string }[] | null) ?? []) map[row.report_id] = row.token;
      setShares(map);
      setLoading(false);
    })();
    return () => { alive = false; };
  }, []);

  async function removeReport(id: string) {
    const { error: e } = await supabase.from("saved_reports").delete().eq("id", id);
    if (!e) setReports((x) => x.filter((r) => r.id !== id));
  }
  async function removePaper(id: string) {
    const { error: e } = await supabase.from("saved_papers").delete().eq("paper_id", id);
    if (!e) setPapers((x) => x.filter((p) => p.paper_id !== id));
  }
  async function copy(text: string) {
    try { await navigator.clipboard.writeText(text); } catch { /* ignore */ }
  }

  async function share(id: string) {
    setNote("");
    let token = shares[id];
    if (!token) {
      if (!window.confirm("Anyone with the link can read this report, including your project description. Create a share link?")) return;
      const { data: u } = await supabase.auth.getUser();
      const uid = u.user?.id;
      if (!uid) { setNote("Please sign in again."); return; }
      const fresh = (crypto.randomUUID() + crypto.randomUUID()).replace(/-/g, "");
      const { error: e } = await supabase.from("shared_reports").insert({ token: fresh, report_id: id, user_id: uid });
      if (e) { setNote("Could not create the link. Make sure the database setup was run."); return; }
      token = fresh;
      setShares((s) => ({ ...s, [id]: fresh }));
    }
    const link = `${window.location.origin}/r/${token}`;
    try { await navigator.clipboard.writeText(link); setNote(`Link copied: ${link}`); }
    catch { setNote(`Your link: ${link}`); }
  }

  async function unshare(id: string) {
    const token = shares[id];
    if (!token) return;
    const { error: e } = await supabase.from("shared_reports").delete().eq("token", token);
    if (!e) {
      setShares((s) => { const c = { ...s }; delete c[id]; return c; });
      setNote("Sharing stopped. The old link no longer works.");
    }
  }

  return (
    <main className="lb">
      <style>{`
        .lb{--bg:#fafaf7;--card:#fff;--text:#1d2433;--muted:#667085;--line:#e4e7ec;--accent:#2f5bea;max-width:760px;margin:0 auto;padding:24px 16px 40px;color:var(--text);font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif}
        @media (prefers-color-scheme:dark){.lb{--bg:#12151c;--card:#1b2030;--text:#eef1f7;--muted:#9aa4b8;--line:#2c3347;--accent:#7b9bff}}
        .lb a{color:var(--accent)}.lb h1{font-size:1.8rem;margin:12px 0 4px}.lb h2{font-size:1.15rem;margin:28px 0 8px}
        .lb .sub{color:var(--muted);margin:0 0 8px;font-size:.92rem}.lb .m{color:var(--muted);font-size:.82rem;word-break:break-word}
        .lb .card{margin-top:10px;padding:14px;border:1px solid var(--line);border-radius:12px;background:var(--card)}
        .lb .card h3{margin:0 0 4px;font-size:1rem;line-height:1.35}
        .lb .acts{display:flex;gap:8px;flex-wrap:wrap;margin-top:10px}
        .lb button{background:none;border:1px solid var(--line);color:var(--text);border-radius:8px;padding:5px 12px;font:inherit;font-size:.82rem;cursor:pointer}
        .lb button.main{border-color:var(--accent);color:var(--accent)}.lb button.del{color:#d92d20}
        .lb a.btnlink{border:1px solid var(--line);border-radius:8px;padding:5px 12px;font-size:.82rem;text-decoration:none}
        .lb details p{margin:8px 0 0;font-size:.9rem}.lb summary{cursor:pointer;color:var(--accent);font-size:.85rem;margin-top:8px}
        .lb .top{display:flex;justify-content:space-between;align-items:center;flex-wrap:wrap;gap:8px}
        .lb .note{margin-top:12px;padding:10px 12px;border-left:3px solid var(--accent);background:var(--card);font-size:.85rem;word-break:break-all}
      `}</style>

      <p><Link href="/">← Back to Scholar Lens</Link></p>
      <h1>My library</h1>
      <p className="sub">Your project outlooks and the papers you have studied are saved here automatically.</p>
      {loading && <p className="m">Loading…</p>}
      {error && <p className="m" style={{ color: "#d92d20" }}>{error}</p>}
      {note && <div className="note">{note}</div>}

      <h2>Project outlooks ({reports.length})</h2>
      {!loading && reports.length === 0 && <p className="m">No saved outlooks yet. Run a Project Outlook and it will appear here.</p>}
      {reports.map((r) => {
        const rep = obj(r.result.report);
        const token = shares[r.id];
        return (
          <div className="card" key={r.id}>
            <h3>{r.project.length > 140 ? r.project.slice(0, 140) + "…" : r.project}</h3>
            <div className="m">{new Date(r.created_at).toLocaleDateString()}{r.horizon ? ` · ${r.horizon}-year outlook` : ""}{r.audience ? ` · ${r.audience}` : ""}{token ? " · shared" : ""}</div>
            {str(rep.summary) ? (
              <details>
                <summary>Show summary</summary>
                <p>{str(rep.summary)}</p>
                {str(rep.bottomLine) ? <p><strong>Bottom line:</strong> {str(rep.bottomLine)}</p> : null}
              </details>
            ) : null}
            <div className="acts">
              <button className="main" onClick={() => share(r.id)}>{token ? "Copy share link" : "Create share link"}</button>
              {token ? <a className="btnlink" href={`/r/${token}`} target="_blank" rel="noopener noreferrer">Open printable report</a> : null}
              {token ? <button onClick={() => unshare(r.id)}>Stop sharing</button> : null}
              <button onClick={() => download(`scholar-lens-outlook-${r.created_at.slice(0, 10)}.md`, reportToMarkdown(r), "text/markdown")}>Download (.md)</button>
              <button onClick={() => copy(reportToMarkdown(r))}>Copy as text</button>
              <button className="del" onClick={() => removeReport(r.id)}>Delete</button>
            </div>
          </div>
        );
      })}

      <div className="top">
        <h2>Papers you studied ({papers.length})</h2>
        {papers.length > 0 && (
          <button className="main" onClick={() => download("scholar-lens-papers.bib", papers.map(bibtex).join("\n\n"), "text/plain")}>Export all as BibTeX</button>
        )}
      </div>
      {!loading && papers.length === 0 && <p className="m">No saved papers yet. Open a Deep dive on any paper and it will appear here.</p>}
      {papers.map((p) => (
        <div className="card" key={p.paper_id}>
          <h3>{p.url ? <a href={p.url} target="_blank" rel="noopener noreferrer">{p.title}</a> : p.title}</h3>
          <div className="m">{[(p.authors ?? []).slice(0, 4).join(", "), p.year, p.venue].filter(Boolean).join(" · ")}</div>
          {p.summary ? (
            <details>
              <summary>Show plain-language summary</summary>
              <p>{p.summary}</p>
            </details>
          ) : null}
          <div className="acts">
            <button onClick={() => copy(bibtex(p))}>Copy BibTeX</button>
            <button className="del" onClick={() => removePaper(p.paper_id)}>Remove</button>
          </div>
        </div>
      ))}
    </main>
  );
}
